// Helper functions

export function getWordsText(pack: string, length: 'short' | 'medium' | 'long' | 'timed'): string {
  let sourceArray = WORDS_ENGLISH;
  
  if (pack === 'filipino') sourceArray = WORDS_FILIPINO;
  if (pack === 'gaming') sourceArray = WORDS_GAMING;
  if (pack === 'mixed') {
    sourceArray = [
      ...WORDS_ENGLISH.slice(0, Math.floor(WORDS_ENGLISH.length * 0.6)),
      ...WORDS_FILIPINO.slice(0, Math.floor(WORDS_FILIPINO.length * 0.5)), // to balance the ratio
      ...WORDS_GAMING.slice(0, Math.floor(WORDS_GAMING.length * 0.5))
    ];
  }

  let count = 15;
  if (length === 'medium') count = 30;
  if (length === 'long') count = 50;
  if (length === 'timed') count = 200;

  // Shuffle and pick
  const result: string[] = [];
  const sourceCopy = [...sourceArray];
  
  for (let i = 0; i < count; i++) {
    if (sourceCopy.length === 0) {
      // Refill if we run out (unlikely unless it's timed mode)
      sourceCopy.push(...sourceArray);
    }
    const randomIndex = Math.floor(Math.random() * sourceCopy.length);
    result.push(sourceCopy[randomIndex]);
    sourceCopy.splice(randomIndex, 1);
  }

  return result.join(' ');
}

export function getQuote(pack: string): Quote {
  let sourceArray = QUOTES_MOTIVATIONAL;
  
  if (pack === 'anime') sourceArray = QUOTES_ANIME;
  if (pack === 'gaming') sourceArray = QUOTES_GAMING;
  if (pack === 'filipino') sourceArray = QUOTES_FILIPINO;

  const randomIndex = Math.floor(Math.random() * sourceArray.length);
  return sourceArray[randomIndex];
}

export function getTimedTarget(): string {
  return getWordsText('mixed', 'timed');
}
